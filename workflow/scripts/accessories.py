def metrics(history):
    """Calculates performance metrics based on a history dataframe generated by the holos environment.

    Args:
        history (pd.DataFrame): Contains --> "time",
                    "observed_power",
                    "desired_power",
                    "drum_1",
                    "drum_2",
                    "drum_3",
                    "drum_4",
                    "drum_5",
                    "drum_6",
                    "drum_7",
                    "drum_8",
                    "actual_power",
                    "c1",
                    "c2",
                    "c3",
                    "c4",
                    "c5",
                    "c6",
                    "Tf",
                    "Tm",
                    "Tc",
                    "Xe",
                    "I",
    """
    if len(history) == 0:
        raise ValueError("metrics() received an empty history dataframe.")
    error = history["desired_power"] - history["actual_power"]
    absolute_error = np.abs(error)
    mae = np.mean(absolute_error)
    cumulative_abs_error = np.sum(absolute_error)
    drum_angles = history[
        ["drum_1", "drum_2", "drum_3", "drum_4", "drum_5", "drum_6", "drum_7", "drum_8"]
    ]
    drum_speeds = np.diff(drum_angles, axis=0)
    absolute_drum_speeds = np.abs(drum_speeds)
    control_effort = np.sum(absolute_drum_speeds)
    mean_control_effort = control_effort / len(history)
    return mae, cumulative_abs_error, control_effort, mean_control_effort


def find_latest_file(folder_path, pattern="*"):
    """Gets the latest file in a path, specifically for grabbing the best trained RL model.

    Args:
        folder_path (Path): path to folder of interest
        pattern (str, optional): string pattern of file names to search for. Defaults to '*'.

    Returns:
        file: file of interest
    """
    try:
        latest_file = sorted(
            folder_path.glob(pattern), key=os.path.getmtime, reverse=True
        )[0]
        return latest_file
    except IndexError:
        raise FileNotFoundError(
            f"No files matching '{pattern}' in '{folder_path}'. "
            "Please ensure models and their associated files have been generated first."
        )


def get_run_folder(run_type, base=Path.cwd() / "runs"):
    """Creates a run folder based on the run_type ("multi-rl", "single-rl", "marl", etc.)

    Args:
        run_type (string): Run name, such as "multi-rl", "single-rl", "marl"
        base (Path, optional): Path to put the run folder in. Defaults to Path.cwd()/'runs'.

    Returns:
        Path: a path to the run folder
    """
    run_folder = base / run_type
    run_folder.mkdir(exist_ok=True, parents=True)
    return run_folder


def episode_length_within_max_time(profile, episode_length, dt):
    max_time = profile.x[-1]
    episode_time = episode_length * dt
    if episode_time > max_time:
        return False
    else:
        return True

def check_spec(history):
    """Checks if a rollout's power trajectory stays within 3% (relative) of desired power.

    Args:
        history (pd.DataFrame): rollout history with 'actual_power' and 'desired_power' columns

    Returns:
        bool: True if actual power never deviates >=3% (relative) from desired power
    """
    pct_dev = np.abs(
        (history["actual_power"] - history["desired_power"]) / history["desired_power"]
    )
    return (pct_dev < 0.03).all()