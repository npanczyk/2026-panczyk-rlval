def metrics(history):
    """Calculates performance metrics based on a history dataframe generated by the holos environment.

    Args:
        history (pd.DataFrame): Contains --> "time",
                    "observed_power",
                    "desired_power",
                    "drum_1",
                    "drum_2",
                    "drum_3",
                    "drum_4",
                    "drum_5",
                    "drum_6",
                    "drum_7",
                    "drum_8",
                    "actual_power",
                    "c1",
                    "c2",
                    "c3",
                    "c4",
                    "c5",
                    "c6",
                    "Tf",
                    "Tm",
                    "Tc",
                    "Xe",
                    "I",
    """
    if len(history) == 0:
        raise ValueError("metrics() received an empty history dataframe.")
    error = history["desired_power"] - history["actual_power"]
    absolute_error = np.abs(error)
    mae = np.mean(absolute_error)
    cumulative_abs_error = np.sum(absolute_error)
    drum_angles = history[
        ["drum_1", "drum_2", "drum_3", "drum_4", "drum_5", "drum_6", "drum_7", "drum_8"]
    ]
    drum_speeds = np.diff(drum_angles, axis=0)
    absolute_drum_speeds = np.abs(drum_speeds)
    control_effort = np.sum(absolute_drum_speeds)
    mean_control_effort = control_effort / len(history)
    return mae, cumulative_abs_error, control_effort, mean_control_effort


def episode_length_within_max_time(profile, episode_length, dt):
    max_time = profile.x[-1]
    episode_time = episode_length * dt
    if episode_time > max_time:
        return False
    else:
        return True
