def test_known_failures_not_revisited(
    bakery, dummy_model, failing_disturbance_dist, tmp_path
):
    """MCTS should spend its iterations looking for new failures, not re-selecting ones it already found.

    Generated by Claude (Opus 5.5), to be verified by Nataly.
    """
    iterations = 50
    tree = run_MCTS(
        environment=bakery,
        model=dummy_model,
        disturbance_dist=failing_disturbance_dist,
        results_path=tmp_path,
        threshold=0.5,
        iterations=iterations,
        percent=False,
    )

    # terminal nodes never get children, so each re-selection only adds 1 to their own N
    nodes = [n for n in tree]
    terminal = [n for n in tree if n.is_terminal()]
    repeat_visits = sum(n.N - 1 for n in terminal)

    print(f"Nodes: {nodes}")
    print(f"Terminal nodes: {terminal}")
    print(f"Repeat visits: {repeat_visits}")

    assert len(terminal) > 0  # the bakery should actually fail
    assert repeat_visits == 0  # we should never revisit terminal nodes


